-- Gera o DDL do schema "public" a partir do catalogo do Postgres. So le, nao altera nada.
--
-- Uso: cole no SQL Editor do Supabase, rode e copie a celula "schema" para
-- supabase/schema.sql. Se o editor cortar o texto, troque o select final pela
-- variante comentada no fim (uma linha por comando) e exporte como CSV.
--
-- Fica de fora: tipos compostos/dominios, grants de tabela (o Supabase os da por
-- padrao) e os schemas do proprio Supabase (auth, storage, extensions...).
with
tabelas as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('r', 'p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
funcoes as (
  select p.oid, p.proname, p.proacl,
         format('public.%I(%s)', p.proname, pg_get_function_identity_arguments(p.oid)) as assinatura,
         -- Funcao cuja assinatura usa o tipo-linha de uma tabela so pode nascer depois dela.
         exists (
           select 1 from pg_type ty
           where ty.typrelid <> 0 and (ty.oid = p.prorettype or ty.oid = any (p.proargtypes::oid[]))
         ) as usa_tabela
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
partes (ordem, nome, ddl) as (
  -- Extensoes so como comentario: quem aplica decide quais existem no destino.
  select 0, e.extname::text, format('-- extensao em uso: %s (schema %s)', e.extname, n.nspname)
  from pg_extension e
  join pg_namespace n on n.oid = e.extnamespace

  union all
  select 1, t.typname::text,
         format('create type public.%I as enum (%s);', t.typname,
                string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  join pg_enum e on e.enumtypid = t.oid
  where n.nspname = 'public'
  group by t.typname

  union all
  select 2, c.relname::text,
         format('create sequence public.%I as %s increment %s minvalue %s maxvalue %s start %s cache %s%s;',
                c.relname, format_type(s.seqtypid, null), s.seqincrement, s.seqmin, s.seqmax,
                s.seqstart, s.seqcache, case when s.seqcycle then ' cycle' else '' end)
  from pg_sequence s
  join pg_class c on c.oid = s.seqrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('i', 'e'))

  union all
  select 3, t.relname::text,
         format(E'create table public.%I (\n%s\n);', t.relname, (
           select string_agg(
                    format('  %I %s%s%s%s',
                           a.attname,
                           format_type(a.atttypid, a.atttypmod),
                           case a.attidentity
                             when 'a' then ' generated always as identity'
                             when 'd' then ' generated by default as identity'
                             else '' end,
                           case
                             when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
                             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                             else '' end,
                           case when a.attnotnull then ' not null' else '' end),
                    E',\n' order by a.attnum)
           from pg_attribute a
           left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
           where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tabelas t

  union all
  select 4, c.relname::text,
         format('alter sequence public.%I owned by public.%I.%I;', c.relname, t.relname, a.attname)
  from pg_depend d
  join pg_class c on c.oid = d.objid and c.relkind = 'S'
  join pg_namespace n on n.oid = c.relnamespace
  join pg_class t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where n.nspname = 'public' and d.deptype = 'a'

  -- Chave primaria, unique, check e exclusion antes das estrangeiras.
  union all
  select 5, t.relname || '.' || co.contype::text || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co
  join tabelas t on t.oid = co.conrelid
  where co.contype in ('p', 'u', 'c', 'x')

  union all
  select 6, t.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co
  join tabelas t on t.oid = co.conrelid
  where co.contype = 'f'

  -- Indices que nao nascem de uma constraint (esses ja vieram acima).
  union all
  select 7, i.relname::text, pg_get_indexdef(ix.indexrelid) || ';'
  from pg_index ix
  join tabelas t on t.oid = ix.indrelid
  join pg_class i on i.oid = ix.indexrelid
  where not exists (
    select 1 from pg_constraint co
    where co.conindid = ix.indexrelid and co.conrelid = ix.indrelid and co.contype in ('p', 'u', 'x')
  )

  -- Funcoes antes das tabelas (defaults, checks e indices podem chamar uma delas); o
  -- corpo nao e validado agora gracas ao check_function_bodies = false do cabecalho.
  union all
  select case when f.usa_tabela then 4 else 2 end, f.assinatura, pg_get_functiondef(f.oid) || ';'
  from funcoes f

  union all
  select 9, c.relname::text,
         format(E'create %s public.%I as\n%s;',
                case c.relkind when 'm' then 'materialized view' else 'view' end,
                c.relname, rtrim(pg_get_viewdef(c.oid, true), ';'))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind in ('v', 'm')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')

  union all
  select 10, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg
  join tabelas t on t.oid = tg.tgrelid
  where not tg.tgisinternal

  -- Triggers em tabelas do proprio Supabase (ex.: auth.users) que chamam funcoes do Trak.
  union all
  select 10, tn.nspname || '.' || c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join pg_namespace tn on tn.oid = c.relnamespace
  join funcoes f on f.oid = tg.tgfoid
  where not tg.tgisinternal and tn.nspname <> 'public'

  union all
  select 11, t.relname::text, format('alter table public.%I enable row level security;', t.relname)
  from tabelas t
  where t.relrowsecurity

  union all
  select 11, t.relname || '~force', format('alter table public.%I force row level security;', t.relname)
  from tabelas t
  where t.relforcerowsecurity

  union all
  select 12, p.tablename || '.' || p.policyname,
         format('create policy %I on public.%I as %s for %s to %s%s%s;',
                p.policyname, p.tablename, lower(p.permissive), lower(p.cmd),
                (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ')
                 from unnest(p.roles) r),
                case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
                case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname = 'public'

  -- Permissao de executar funcoes: so os papeis da API (os internos do Supabase ficam de fora).
  union all
  select 13, f.assinatura,
         format('revoke all on function %s from public, anon, authenticated, service_role;', f.assinatura)
  from funcoes f
  where f.proacl is not null

  union all
  select 14, f.assinatura || '.' || coalesce(pg_get_userbyid(nullif(a.grantee, 0)), 'public'),
         format('grant execute on function %s to %s;', f.assinatura,
                case when a.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(a.grantee)) end)
  from funcoes f
  cross join lateral aclexplode(f.proacl) a
  where a.privilege_type = 'EXECUTE'
    and (a.grantee = 0 or pg_get_userbyid(a.grantee) in ('anon', 'authenticated', 'service_role'))
)
select format(E'-- Retrato do schema public extraido em %s por supabase/ferramentas/extrair-schema.sql.\n-- Inclui as migracoes ate: PREENCHER\n\nset check_function_bodies = false;\n\n', now()::date)
       || string_agg(ddl, E'\n\n' order by ordem, nome) as schema
from partes;

